// Regenerates the monday calendar's Taiwan public-holiday table from the DGPA office calendar
// (mirrored by github.com/ruyut/TaiwanCalendar). Rerun once the next year's calendar is out:
//   node config/scripts/generate-taiwan-public-holidays.mjs 2025 2027
import { writeFileSync } from 'node:fs'
import path from 'node:path'

const SOURCE_URL = 'https://cdn.jsdelivr.net/gh/ruyut/TaiwanCalendar/data'
const OUTPUT_PATH = path.join(
  import.meta.dirname,
  '../../src/renderer/src/components/monday/taiwan-public-holidays.ts'
)
const DATE_PATTERN = /^\d{8}$/
const UNSAFE_NAME_PATTERN = /['\\\n]/

function parseYearRange(argv) {
  const [from, to = from] = argv.map(Number)
  if (!Number.isInteger(from) || !Number.isInteger(to) || from > to) {
    throw new Error('usage: generate-taiwan-public-holidays.mjs <fromYear> [toYear]')
  }
  return Array.from({ length: to - from + 1 }, (_, index) => from + index)
}

function toHolidayEntry(day, year) {
  if (typeof day?.date !== 'string' || !DATE_PATTERN.test(day.date)) {
    throw new Error(`${year}: unexpected day record ${JSON.stringify(day)}`)
  }
  // Plain weekends are holidays with no description; only named days are public holidays.
  if (day.isHoliday !== true || typeof day.description !== 'string' || !day.description) {
    return null
  }
  if (UNSAFE_NAME_PATTERN.test(day.description)) {
    throw new Error(`${year}: unexpected holiday name ${JSON.stringify(day.description)}`)
  }
  const iso = `${day.date.slice(0, 4)}-${day.date.slice(4, 6)}-${day.date.slice(6, 8)}`
  return [iso, day.description]
}

async function fetchYear(year) {
  const response = await fetch(`${SOURCE_URL}/${year}.json`)
  if (!response.ok) {
    throw new Error(`${year}: HTTP ${response.status}`)
  }
  const days = await response.json()
  if (!Array.isArray(days) || days.length < 365) {
    throw new Error(`${year}: expected a full year of days`)
  }
  return days.map((day) => toHolidayEntry(day, year)).filter((entry) => entry !== null)
}

const years = parseYearRange(process.argv.slice(2))
const entries = (await Promise.all(years.map(fetchYear))).flat()
const body = entries.map(([iso, name]) => `  '${iso}': '${name}'`).join(',\n')
writeFileSync(
  OUTPUT_PATH,
  `// Generated by config/scripts/generate-taiwan-public-holidays.mjs (${years[0]}–${years.at(-1)}); do not edit.
export const TAIWAN_PUBLIC_HOLIDAYS: Readonly<Record<string, string>> = {
${body}
}
`
)
console.log(`wrote ${entries.length} holidays for ${years.join(', ')} to ${OUTPUT_PATH}`)
