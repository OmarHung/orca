#!/usr/bin/env node
// Pins the Vue navigation server (vtsls + @vue/typescript-plugin) for Orca's installer.
// Resolves the dependency closure with npm, downloads every tarball, checks it against npm's
// sha512 integrity, and writes src/main/code-navigation/vue-language-server-manifest.ts with
// each package's node_modules path, URL, SHA-256 and size. Bump the versions below and rerun.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'

const PACKAGES = { '@vtsls/language-server': '0.3.0', '@vue/typescript-plugin': '3.3.11' }
// Why tied to vtsls: Orca installs the closure under this name and version.
const SET_VERSION = `${PACKAGES['@vtsls/language-server']}+vue.${PACKAGES['@vue/typescript-plugin']}`

const repoRoot = path.resolve(import.meta.dirname, '..', '..', '..')
const output = path.join(repoRoot, 'src/main/code-navigation/vue-language-server-manifest.ts')

function resolveLock() {
  const dir = mkdtempSync(path.join(tmpdir(), 'orca-vue-manifest-'))
  try {
    writeFileSync(
      path.join(dir, 'package.json'),
      JSON.stringify({ name: 'orca-vue-server', private: true, dependencies: PACKAGES })
    )
    execFileSync(
      'npm',
      ['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund'],
      { cwd: dir, stdio: 'inherit', shell: process.platform === 'win32' }
    )
    return JSON.parse(readFileSync(path.join(dir, 'package-lock.json'), 'utf8'))
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

async function pin(lockPath, entry) {
  if (entry.hasInstallScript || entry.os || entry.cpu) {
    throw new Error(`${lockPath} needs install scripts or a platform; the installer cannot pin it`)
  }
  const response = await fetch(entry.resolved)
  if (!response.ok) {
    throw new Error(`HTTP ${response.status} for ${entry.resolved}`)
  }
  const payload = Buffer.from(await response.arrayBuffer())
  const [algorithm, expected] = entry.integrity.split('-')
  const actual = createHash(algorithm).update(payload).digest('base64')
  if (algorithm !== 'sha512' || actual !== expected) {
    throw new Error(`${lockPath} does not match npm's integrity ${entry.integrity}`)
  }
  return {
    path: lockPath,
    url: entry.resolved,
    sha256: createHash('sha256').update(payload).digest('hex'),
    sizeBytes: payload.length
  }
}

const lock = resolveLock()
const entries = Object.entries(lock.packages).filter(([lockPath]) => lockPath !== '')
const pinned = []
for (const [lockPath, entry] of entries) {
  pinned.push(await pin(lockPath, entry))
}
pinned.sort((a, b) => a.path.localeCompare(b.path))

const today = new Date().toISOString().slice(0, 10)
const lines = pinned.map(
  (artifact) =>
    `    {\n      path: '${artifact.path}',\n      url: '${artifact.url}',\n      sha256: '${artifact.sha256}',\n      sizeBytes: ${artifact.sizeBytes}\n    }`
)
writeFileSync(
  output,
  `// Generated by config/scripts/fork-maintenance/generate-vue-language-server-manifest.mjs; do not edit.
import { VUE_LANGUAGE_SERVER_DIR_NAME } from '../../shared/code-navigation/code-navigation-types'
import type { NpmPackageSet } from './npm-package-set-installer'

// Hashes computed ${today} from npm tarballs checked against their sha512 integrity.
export const VUE_LANGUAGE_SERVER_PACKAGES: NpmPackageSet = {
  name: VUE_LANGUAGE_SERVER_DIR_NAME,
  version: '${SET_VERSION}',
  packages: [
${lines.join(',\n')}
  ]
}
`
)
console.log(`Pinned ${pinned.length} packages to ${path.relative(repoRoot, output)}`)
